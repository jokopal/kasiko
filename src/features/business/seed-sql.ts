import { normalizeLayout } from './config'
import { findTemplate } from './templates'

// Builds supabase/seed.sql from the same template the app uses, so the database seed can
// never drift from the template (seed-sql.test.ts compares the file on every run).
// LOCAL DEVELOPMENT ONLY: `supabase db reset` runs it; it is never pushed to a remote
// project. Production owners are created by the bootstrap script (decision #22).

export const SEED_IDS = {
  owner: '5a1a0000-0000-4000-8000-000000000001',
  cashier: '5a1a0000-0000-4000-8000-000000000002',
  business: '5a1a0000-0000-4000-8000-0000000000b1',
} as const

/** Local-only accounts; the password meets the auth rule (≥ 8, letters + digits). */
export const SEED_ACCOUNTS = [
  { id: SEED_IDS.owner, email: 'owner@saimara.test', password: 'saimara123', role: 'owner' },
  { id: SEED_IDS.cashier, email: 'kasir@saimara.test', password: 'saimara123', role: 'cashier' },
] as const

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`
const json = (value: unknown) => `${literal(JSON.stringify(value))}::jsonb`

export function buildSeedSql(): string {
  const template = findTemplate('cuci-mobil')
  const { business } = SEED_IDS
  const users = SEED_ACCOUNTS.map(
    (a) => `  (
    '00000000-0000-0000-0000-000000000000', ${literal(a.id)}, 'authenticated', 'authenticated',
    ${literal(a.email)}, extensions.crypt(${literal(a.password)}, extensions.gen_salt('bf')),
    now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', ''
  )`,
  ).join(',\n')
  const identities = SEED_ACCOUNTS.map(
    (a) =>
      `  (${literal(a.id)}, ${literal(a.id)}, ${json({ sub: a.id, email: a.email })}, 'email', ${literal(a.id)}, now(), now(), now())`,
  ).join(',\n')

  return `-- Generated by src/features/business/seed-sql.ts from the "${template.name}" template.
-- Do not edit by hand. Regenerate: npx vitest run src/features/business/seed-sql.test.ts -u
--
-- LOCAL DEVELOPMENT ONLY (supabase db reset). Accounts:
${SEED_ACCOUNTS.map((a) => `--   ${a.role.padEnd(7)} ${a.email} / ${a.password}`).join('\n')}
-- Catalog prices are template placeholders; the owner builds the real list (open question #5).

insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token
) values
${users};

insert into auth.identities (
  id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at
) values
${identities};

insert into public.businesses (
  id, owner_id, name, address, phone, receipt_footer, primary_color, receipt_prefix, timezone
) values (
  ${literal(business)}, ${literal(SEED_IDS.owner)}, 'Saimara', '', '',
  'Terima kasih, sampai jumpa lagi!', '#0e7490', 'SMR', 'Asia/Jakarta'
);

insert into public.business_members (business_id, user_id, role) values
  (${literal(business)}, ${literal(SEED_IDS.owner)}, 'owner'),
  (${literal(business)}, ${literal(SEED_IDS.cashier)}, 'cashier');

insert into public.business_configs (business_id, template_id, dashboard) values (
  ${literal(business)}, ${literal(template.id)},
  ${json(normalizeLayout(template.dashboard))}
);

select public.apply_template_rows(
  ${literal(business)},
  ${json({ id: template.id, catalog: template.catalog, expenseCategories: template.expenseCategories })}
);
`
}
